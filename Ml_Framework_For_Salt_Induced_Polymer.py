import pandas as pd
import numpy as np
from sklearn.model_selection import LeaveOneGroupOut
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error, r2_score, mean_absolute_error
from sklearn.svm import SVR
from sklearn.ensemble import ExtraTreesRegressor, RandomForestRegressor, GradientBoostingRegressor

# Optional: try importing XGBoost / LightGBM if installed
try:
    import xgboost as xgb
    has_xgb = True
except ImportError:
    has_xgb = False

try:
    import lightgbm as lgb
    has_lgb = True
except ImportError:
    has_lgb = False

# 1. Load engineered dataset
df = pd.read_csv('/content/drive/MyDrive/lcst_engineered_dataset.csv')

# 2. Create Salt Group identifier for Leave-One-Salt-Out (LOSO) CV
df['Salt_Group'] = df['cation'].astype(str) + "_" + df['anion'].astype(str)

# 3. Define physics-informed feature subset
feature_cols = [
    'Cp', 'Cs_wt_pct',
    'dG_net', 'dH_net', 'B_net', 'Vs_net',
    'Ionic_Strength_Factor', 'Cp_Cs_interaction'
]

X = df[feature_cols]
y = df['LCST_degC']
groups = df['Salt_Group']

# 4. Define candidate benchmark models
models = {
    'SVR (RBF Kernel)': SVR(C=10.0, epsilon=0.1),
    'ExtraTrees': ExtraTreesRegressor(n_estimators=100, random_state=42),
    'RandomForest': RandomForestRegressor(n_estimators=100, random_state=42),
    'GradientBoosting': GradientBoostingRegressor(n_estimators=100, learning_rate=0.05, random_state=42)
}

if has_xgb:
    models['XGBoost'] = xgb.XGBRegressor(n_estimators=100, learning_rate=0.05, random_state=42)
if has_lgb:
    models['LightGBM'] = lgb.LGBMRegressor(n_estimators=100, learning_rate=0.05, random_state=42, verbose=-1)

# 5. Run Leave-One-Salt-Out Cross-Validation
logo = LeaveOneGroupOut()
summary_results = []

for name, model in models.items():
    y_true_all, y_pred_all = [], []

    for train_idx, test_idx in logo.split(X, y, groups):
        X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
        y_train, y_test = y.iloc[train_idx], y.iloc[test_idx]

        # Scale features inside CV loop to prevent data leakage
        scaler = StandardScaler()
        X_train_scaled = scaler.fit_transform(X_train)
        X_test_scaled = scaler.transform(X_test)

        # Train & Predict
        model.fit(X_train_scaled, y_train)
        preds = model.predict(X_test_scaled)

        y_true_all.extend(y_test)
        y_pred_all.extend(preds)

    rmse = np.sqrt(mean_squared_error(y_true_all, y_pred_all))
    mae = mean_absolute_error(y_true_all, y_pred_all)
    r2 = r2_score(y_true_all, y_pred_all)

    summary_results.append({
        'Model': name,
        'LOSO RMSE (°C)': round(rmse, 3),
        'LOSO MAE (°C)': round(mae, 3),
        'LOSO R²': round(r2, 3)
    })

# Display benchmark comparison table
benchmark_df = pd.DataFrame(summary_results).sort_values(by='LOSO RMSE (°C)')
print("\n=== Leave-One-Salt-Out (LOSO) Model Benchmark Results ===")
print(benchmark_df.to_string(index=False))

