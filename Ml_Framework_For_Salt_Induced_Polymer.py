import pandas as pd
import numpy as np
from scipy import stats
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Load your engineered dataset
df = pd.read_csv('/content/drive/MyDrive/lcst_engineered_dataset.csv')

# 2. Select numerical columns (excluding sample index)
num_cols = df.select_dtypes(include=[np.number]).columns.tolist()
if 'No' in num_cols:
    num_cols.remove('No')

# 3. Perform Shapiro-Wilk test and calculate Skewness/Kurtosis
results = []
for col in num_cols:
    data = df[col].dropna()
    stat, p_val = stats.shapiro(data)
    skew = stats.skew(data)
    kurt = stats.kurtosis(data)

    results.append({
        'Feature': col,
        'Shapiro_Stat': round(stat, 4),
        'p_value': round(p_val, 5),
        'Is_Normal (p>0.05)': 'Yes' if p_val > 0.05 else 'No',
        'Skewness': round(skew, 2),
        'Kurtosis': round(kurt, 2)
    })

# Convert to DataFrame and display
res_df = pd.DataFrame(results)
print("=== Shapiro-Wilk Normality Summary ===")
print(res_df.to_string(index=False))

# 4. Generate Visualizations (Histograms & Q-Q Plot)
plt.figure(figsize=(6, 6))

